import { writeFile } from "node:fs/promises";
import {
  argbFromHex,
  hexFromArgb,
  TonalPalette,
} from "@material/material-color-utilities";
// Development-time generation; no palette engine ships to the browser.
const seeds = {
  green: "#23864e",
  blue: "#4285f4",
  yellow: "#fbbc04",
  coral: "#ea6652",
  purple: "#9273cc",
};
const tokens = Object.entries(seeds).flatMap(([name, seed]) => {
  const palette = TonalPalette.fromInt(argbFromHex(seed));
  return [10, 30, 40, 80, 90, 95, 98].map(
    (tone) =>
      "  --md-" +
      name +
      "-" +
      tone +
      ": " +
      hexFromArgb(palette.tone(tone)) +
      ";",
  );
});
await writeFile(
  new URL("../app/material-tokens.css", import.meta.url),
  "/* Generated by npm run design:tokens. Material Color Utilities / HCT. */\n:root {\n" +
    tokens.join("\n") +
    "\n}\n",
);
console.log("Material tonal palettes generated.");
